// Writes every line the doll can say to tests/e2e/out/avatar-review/lines.md, for the owner's veto.
// npx tsx tests/e2e/avatar-review-lines.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { COMBOS, GENERIC_LINES, ITEMS, getItem } from '../../client/src/avatar/catalog';

const ROOT = resolve(import.meta.dirname, '../..');
const guide = readFileSync(resolve(ROOT, 'design/punchlines.he.md'), 'utf8');
const voice = readFileSync(resolve(ROOT, 'client/src/avatar/dressing-voice.ts'), 'utf8');
const SLOT = { HEAD: 'ראש', EYES: 'עיניים', EARS: 'אוזניים', FACE: 'פנים', NECK: 'צוואר' } as const;
const out: string[] = [];
out.push('# Shimi dressing room: every line the doll says', '');
out.push('Generated by `npx tsx tests/e2e/avatar-review-lines.ts` from the catalog. Voice guide: `design/punchlines.he.md`.');
out.push('Source: **guide** = copied word for word from the guide (the owner\'s own three lines are marked there); **maker** = written by the accessory makers and kept; **review** = rewritten in the release review. Strike any line and it is removed from the item in `client/src/avatar/catalog*.ts`.', '');
const REVIEW = new Set([
  'ביסטרו בפלורנטין. שולחן אחד, תור עד יפו.', 'סבתא סרגה. אני הקולקציה.', 'מציל בחוף גורדון. שומר בעיקר על האבטיח.',
  'מנהל עבודה. השיפוץ ייגמר כשאני אגיד.', 'כוכב בתלת־ממד. גם בפרופיל אני מושלם.', 'בקר טיסה בנתב״ג. הטיסה מתעכבת בגללי.',
]);
out.push('## Accessories', '', '| id | slot | accessory | line | source |', '| --- | --- | --- | --- | --- |');
for (const it of ITEMS) for (const line of it.lines ?? []) {
  out.push(`| ${it.id} | ${SLOT[it.slot]} | ${it.name} | ${line} | ${guide.includes(line) ? 'guide' : REVIEW.has(line) ? 'review' : 'maker'} |`);
}
out.push('', '## Combination lines (win over the single lines when the item that completes the set lands)', '', '| worn together | line | source |', '| --- | --- | --- |');
const WHEN = { tower3: 'שלושה כובעים במגדל', bare: 'הכול נוער (בובה חשופה)', full: 'משהו בכל משבצת' } as const;
for (const c of COMBOS) for (const line of c.lines) {
  out.push(`| ${c.ids !== undefined ? c.ids.map((id) => getItem(id)?.name ?? id).join(' + ') : WHEN[c.when ?? 'bare']} | ${line} | guide |`);
}
out.push('', '## Generic reactions (only for an accessory with no line of its own; none today)', '');
GENERIC_LINES.forEach((l, i) => out.push(`${i + 1}. ${l}`));
out.push('', '## Room lines (dressing-voice.ts: greeting, tower, taking off, shake, random, plate, done)', '', '| when | line | source |', '| --- | --- | --- |');
const block = voice.slice(voice.indexOf('export const LINES'), voice.indexOf('export const BURST'));
for (const m of block.matchAll(/^\s+(\w+): (.+)$/gm)) {
  for (const s of (m[2] ?? '').matchAll(/['`]([^'`]*[֐-׿][^'`]*)['`]/g)) out.push(`| ${m[1]} | ${s[1]} | ${guide.includes(s[1] ?? '') ? 'guide' : 'review'} |`);
}
out.push('', '## Burst words', '');
const bursts = voice.slice(voice.indexOf('export const BURST'), voice.indexOf('const turn'));
out.push([...bursts.matchAll(/'([^']*[֐-׿][^']*)'/g)].map((m) => m[1]).filter((v, i, a) => a.indexOf(v) === i).join(' · '));
mkdirSync(resolve(ROOT, 'tests/e2e/out/avatar-review'), { recursive: true });
writeFileSync(resolve(ROOT, 'tests/e2e/out/avatar-review/lines.md'), out.join('\n') + '\n');
console.log('lines:', out.length);
